const crypto = require("crypto");

const AUTH_PROVIDERS = Object.freeze({
  GOOGLE: "google",
  APPLE: "apple",
  EMAIL: "email",
});

function buildStableUserId(provider, providerUserId, fallbackId) {
  if (provider && providerUserId) {
    return `${provider}:${providerUserId}`;
  }

  return fallbackId || crypto.randomUUID();
}

function getSupportedAuthProviders() {
  return Object.values(AUTH_PROVIDERS);
}

function isSupportedAuthProvider(provider) {
  return getSupportedAuthProviders().includes(provider);
}

function normalizeProfileText(value) {
  return typeof value === "string" ? value.trim() : "";
}

function isEmailLikeValue(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(normalizeProfileText(value));
}

function extractReadableEmailPrefix(email) {
  const prefix = normalizeProfileText(email).split("@")[0] || "";
  const cleaned = prefix
    .replace(/[._+-]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase())
    .replace(/\s+/g, " ")
    .trim();

  return cleaned || "FloMind User";
}

function getAppleDisplayNameFallback(email) {
  return email ? extractReadableEmailPrefix(email) : "FloMind User";
}

function isAutoGeneratedAppleDisplayName(displayName, email) {
  const normalizedDisplayName = normalizeProfileText(displayName);
  const normalizedEmail = normalizeProfileText(email);

  if (!normalizedDisplayName) {
    return true;
  }

  if (normalizedEmail && normalizedDisplayName.toLowerCase() === normalizedEmail.toLowerCase()) {
    return true;
  }

  if (isEmailLikeValue(normalizedDisplayName)) {
    return true;
  }

  return false;
}

function createUser({
  id,
  provider,
  providerUserId,
  name = null,
  email = null,
  googleName = null,
  googlePicture = null,
  plan = "free",
  displayName = null,
  avatarUrl = null,
  theme = "system",
  googleTokens = null,
  stripeCustomerId = null,
  stripeSubscriptionId = null,
  stripeSubscriptionStatus = null,
  stripePriceId = null,
  billingInterval = null,
  createdAt = new Date().toISOString(),
}) {
  if (!isSupportedAuthProvider(provider)) {
    throw new Error(`Unsupported auth provider: ${provider}`);
  }

  return {
    id: buildStableUserId(provider, providerUserId, id),
    provider,
    providerUserId,
    name,
    email,
    googleName,
    googlePicture,
    plan,
    displayName,
    avatarUrl,
    theme,
    googleTokens,
    stripeCustomerId,
    stripeSubscriptionId,
    stripeSubscriptionStatus,
    stripePriceId,
    billingInterval,
    createdAt,
  };
}

function buildSessionUser(user) {
  return {
    id: user.id,
    provider: user.provider,
    providerUserId: user.providerUserId,
    name: user.displayName || user.googleName || user.name,
    email: user.email,
    googleName: user.googleName || null,
    googlePicture: user.googlePicture || null,
    picture: user.avatarUrl || user.googlePicture || null,
    plan: user.plan || "free",
    displayName: user.displayName || null,
    avatarUrl: user.avatarUrl || null,
    theme: user.theme || "system",
    billingInterval: user.billingInterval || null,
    createdAt: user.createdAt,
  };
}

module.exports = {
  AUTH_PROVIDERS,
  buildStableUserId,
  buildSessionUser,
  createUser,
  getAppleDisplayNameFallback,
  getSupportedAuthProviders,
  isAutoGeneratedAppleDisplayName,
  isSupportedAuthProvider,
};
